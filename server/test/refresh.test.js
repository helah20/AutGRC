/**
 * Generated documents follow the platform: a draft is rebuilt with the current
 * knowledge base, a published document is marked and updated only through a
 * revision, and a section a person edited or locked is never overwritten.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'autgrc-refresh-'));
process.env.AUTGRC_DATA_DIR = tmpDir;
process.env.AUTGRC_DB_FILE = path.join(tmpDir, 'test.db');
process.env.JWT_SECRET = 'test-secret-for-the-refresh-suite-only';

const { q, nowIso, fromJson, toJson } = await import('../src/db/index.js');
const { syncCatalogue } = await import('../src/db/seed.js');
const { generatePackage } = await import('../src/services/generator.js');
const { refreshGeneratedDocuments, refreshDocument, contentRevision } = await import('../src/services/refresh.js');

syncCatalogue();
q.run(`INSERT INTO org_profile (id, org_name, applicable_frameworks, updated_at) VALUES (1, 'Test Org', ?, ?)`, toJson(['NCA-ECC', 'NCA-OSMACC']), nowIso());
q.run(`INSERT INTO users (id, email, name, password_hash, role, created_at, updated_at) VALUES ('u1','u1@t','U1','x','grc_manager',?,?)`, nowIso(), nowIso());

const pkg = generatePackage({ domainKey: 'social_media_security', docTypes: ['policy'], frameworkCodes: ['NCA-ECC', 'NCA-OSMACC'], org: { org_name: 'Test Org' }, userId: 'u1' });
const docId = q.get('SELECT id FROM documents WHERE package_id = ?', pkg.packageId).id;
const section = (key) => q.get('SELECT * FROM document_sections WHERE document_id = ? AND section_key = ?', docId, key);
const meta = () => fromJson(q.get('SELECT generation_meta FROM documents WHERE id = ?', docId).generation_meta, {});

// Make the document look as if it was generated by an older platform.
function age() {
  q.run("UPDATE document_sections SET body = '<p>Old scope covering every system.</p>', provenance = 'ai_recommendation' WHERE document_id = ? AND section_key = 'scope'", docId);
  q.run("UPDATE document_sections SET body = '<p>The organisation wrote this.</p>', provenance = 'user_input' WHERE document_id = ? AND section_key = 'objectives'", docId);
  q.run('UPDATE documents SET generation_meta = ? WHERE id = ?', toJson({ ...meta(), contentRevision: 'older' }), docId);
}

test('a new document records what it was built from', () => {
  assert.equal(meta().contentRevision, contentRevision());
});

test('a draft is rebuilt, keeping what a person wrote', () => {
  age();
  const result = refreshGeneratedDocuments();
  assert.equal(result.updated, 1);
  assert.match(section('scope').body, /official accounts on every social media platform/);
  assert.equal(section('objectives').body, '<p>The organisation wrote this.</p>', 'an edited section is kept');
  assert.equal(meta().contentRevision, contentRevision());
  const version = q.get("SELECT * FROM document_versions WHERE document_id = ? AND change_type = 'regenerated'", docId);
  assert.ok(version, 'the previous text is kept as a version');
  assert.match(version.snapshot, /Old scope covering every system/);
  assert.equal(refreshGeneratedDocuments().updated, 0, 'a second start changes nothing');
});

test('a published document is marked, not changed, until a revision applies the update', () => {
  age();
  q.run("UPDATE documents SET status = 'published' WHERE id = ?", docId);
  const result = refreshGeneratedDocuments();
  assert.equal(result.flagged, 1);
  assert.equal(section('scope').body, '<p>Old scope covering every system.</p>', 'approved text does not change on its own');
  assert.equal(meta().updateAvailable, true);

  const applied = refreshDocument(docId, { id: 'u1', name: 'U1' });
  assert.ok(applied.changed > 0);
  assert.equal(q.get('SELECT status FROM documents WHERE id = ?', docId).status, 'under_revision');
  assert.match(section('scope').body, /official accounts on every social media platform/);
  assert.equal(meta().updateAvailable, false);
});
