/**
 * The internal audit report and the management review minutes, built from the
 * seeded data set. What matters: a nonconformity without an action is called
 * out, the audit opinion is left to the auditor, and the next review reads the
 * previous review's decisions back.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'autgrc-assurance-'));
process.env.AUTGRC_DATA_DIR = tmpDir;
process.env.AUTGRC_DB_FILE = path.join(tmpDir, 'test.db');
process.env.JWT_SECRET = 'test-secret-for-the-assurance-records-suite-only';

const { q, nowIso } = await import('../src/db/index.js');
const { runSeed } = await import('../src/db/seed.js');
const { auditReportPayload, reviewMinutesPayload } = await import('../src/services/assurance-records.js');
const { managementReviewInputs } = await import('../src/services/management-reports.js');
const { buildDocx } = await import('../src/services/export-docx.js');
const { htmlToText } = await import('../src/services/html.js');

const log = console.log;
console.log = () => {};
await runSeed();
console.log = log;

const text = (payload, heading) => htmlToText(payload.sections.find((s) => s.heading === heading).body);

test('the audit report states results and calls out nonconformities without an action', async () => {
  const assessment = q.get('SELECT * FROM assessments LIMIT 1');
  const payload = auditReportPayload(assessment.id);
  const nonCompliant = q.get("SELECT COUNT(*) AS n FROM gap_items WHERE assessment_id = ? AND status = 'non_compliant'", assessment.id).n;
  assert.ok(nonCompliant > 0, 'the seed leaves non-compliant items');
  assert.match(text(payload, 'Summary of Results'), new RegExp(`Non-compliant\\s+${nonCompliant}`));
  assert.match(text(payload, 'Corrective Actions'), /without a corrective action/);
  assert.match(text(payload, 'Audit Conclusion'), /not generated by the platform/, 'the opinion is the auditor\'s');

  // An action on one nonconformity removes it from the uncovered list, and its
  // root cause appears in the report.
  const item = q.get("SELECT * FROM gap_items WHERE assessment_id = ? AND status = 'non_compliant' LIMIT 1", assessment.id);
  const owner = q.get("SELECT id FROM users WHERE status = 'active' LIMIT 1");
  q.run(`INSERT INTO corrective_actions (id, action_id, title, source_type, source_id, owner_id, priority, due_date, status, progress, root_cause, created_at, updated_at)
         VALUES ('act_t1','CA-9001','Close the gap','gap_item',?,?, 'high','2099-01-01','open',0,'No owner was assigned to the control.',?,?)`,
    item.id, owner.id, nowIso(), nowIso());
  const after = text(auditReportPayload(assessment.id), 'Corrective Actions');
  assert.match(after, /CA-9001/);
  assert.match(after, /No owner was assigned/);
  assert.ok(!new RegExp(`no corrective action: [^.]*\\b${item.requirement_ref}\\b`).test(after), 'the covered item is no longer listed');

  const docx = await buildDocx({ ...auditReportPayload(assessment.id), org: { org_name: 'Test' } });
  assert.ok(docx.byteLength > 5000, 'the report renders to Word');
  assert.equal(auditReportPayload('asm_missing'), null);
});

test('the next review reads back the decisions of the last closed one', () => {
  const at = nowIso();
  const owner = q.get("SELECT id FROM users WHERE status = 'active' LIMIT 1");
  q.run(`INSERT INTO management_reviews (id, review_id, held_on, forum, inputs_snapshot, status, closed_at, created_at, updated_at)
         VALUES ('mrv_t1','MR-0001','2026-01-15','Cybersecurity Supervisory Committee',?,'closed',?,?,?)`,
    JSON.stringify({ ...managementReviewInputs(), capturedAt: at }), at, at, at);
  q.run(`INSERT INTO corrective_actions (id, action_id, title, source_type, owner_id, priority, due_date, status, progress, created_at, updated_at)
         VALUES ('act_t2','CA-9002','Fund a second SOC analyst','manual',?,'medium','2000-01-01','open',0,?,?)`, owner.id, at, at);
  q.run(`INSERT INTO management_review_decisions (id, review_id, position, category, decision, owner_id, due_date, action_id, created_at)
         VALUES ('mrd_t1','mrv_t1',1,'resources','Fund a second SOC analyst',?,'2000-01-01','act_t2',?),
                ('mrd_t2','mrv_t1',2,'improvement','Report phishing metrics quarterly',NULL,NULL,NULL,?)`, owner.id, at, at);

  const row = managementReviewInputs().rows.find((r) => r[1] === 'ISO 9.3.2 a');
  assert.match(row[2], /MR-0001 \(2026-01-15\) recorded 2 decision\(s\), 1 with an action: 0 verified, 1 open \(1 overdue\)/);
  assert.equal(row[4], 'Decision needed');

  const minutes = reviewMinutesPayload('MR-0001');
  assert.match(text(minutes, 'Decisions and Actions'), /CA-9002 \(open\)/);
  assert.match(text(minutes, 'Inputs Considered'), /ISO 9\.3\.2 g/, 'the snapshot of the inputs is in the minutes');
});
